"""Independent judge: re-grade the saved answers with Claude and compare with the GPT judge.

The answers were generated by gpt-5.6-luna and first graded by gpt-5.6-luna (eval/judge.py),
so generator and judge came from one model family. This script re-grades the SAME saved
answers (nothing is regenerated or re-retrieved) with a Claude model, using the identical
rubric (judge._SYSTEM) and the identical grading message (judge.grading_prompt).

Blinding, as in judge.py: the judge sees only the question, the reference answer and one
answer. It never sees the system name, retrieval scores, sources, or the other system's
answer; answers are graded one at a time, in a seeded random order. The only remaining
signal is the answers' own wording, which leakage_audit() measures and reports.

Outputs go to results/claude-judge/<dir>/ (the GPT-judge files are never touched):
  judged.json        one verdict per (question, system)
  judge_summary.*    same table as the GPT judge
  comparison.md/json both judges side by side, agreement, Cohen's kappa, disagreements

Usage:
  python eval/claude_judge.py                       # both result sets, claude-opus-5-5
  python eval/claude_judge.py results/llm-cards --model claude-sonnet-5-5
Needs ANTHROPIC_API_KEY (in .env or the environment).
"""
from __future__ import annotations

import argparse
import json
import random
import re
import sys
from collections import Counter
from pathlib import Path
from typing import Literal

import anthropic
from dotenv import load_dotenv
from pydantic import BaseModel

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "eval"))
load_dotenv(ROOT / ".env")

from judge import _SYSTEM, grading_prompt, summarize  # noqa: E402

LABELS = ("correct", "partial", "incorrect")
OUT = ROOT / "results" / "claude-judge"


class Verdict(BaseModel):
    verdict: Literal["correct", "partial", "incorrect"]
    reason: str


def grade(client: anthropic.Anthropic, model: str, user: str) -> dict:
    """One blind verdict. A refusal is recorded as such, never silently re-routed to
    another model: every verdict in the file must come from the named judge."""
    resp = client.messages.parse(model=model, max_tokens=4000, system=_SYSTEM,
                                 messages=[{"role": "user", "content": user}],
                                 output_format=Verdict,
                                 output_config={"effort": "medium"})   # pinned for reruns
    if resp.stop_reason == "refusal" or resp.parsed_output is None:
        return {"verdict": "incorrect", "reason": f"judge returned no verdict ({resp.stop_reason})",
                "judge_error": True}
    return resp.parsed_output.model_dump()


def judge_dir(src: Path, client: anthropic.Anthropic, model: str) -> Path:
    answers = json.loads((src / "answers.json").read_text())
    qs = {q["id"]: q for q in json.loads((ROOT / "eval/questions.json").read_text())["questions"]}
    out = OUT / src.name
    out.mkdir(parents=True, exist_ok=True)
    path = out / "judged.json"
    cache = {(j["id"], j["system"]): j for j in
             (json.loads(path.read_text()) if path.exists() else []) if j.get("judge") == model}
    todo = [a for a in answers if (a["id"], a["system"]) not in cache]
    random.Random(1).shuffle(todo)          # order carries no system signal
    for n, a in enumerate(todo, 1):
        v = grade(client, model, grading_prompt(qs[a["id"]], a["answer"]))
        cache[(a["id"], a["system"])] = {"id": a["id"], "type": a["type"], "system": a["system"],
                                         "judge": model, **v}
        path.write_text(json.dumps(list(cache.values()), indent=1))   # resumable
        print(f"[{src.name}] {n}/{len(todo)}", end="\r")
    rows, md = summarize(list(cache.values()))
    (out / "judge_summary.json").write_text(json.dumps(rows, indent=1))
    (out / "judge_summary.md").write_text(md + "\n")
    return out


# ------------------------------------------------------------------ comparison

def cohen_kappa(a: list[str], b: list[str]) -> float:
    n = len(a)
    po = sum(x == y for x, y in zip(a, b)) / n
    ca, cb = Counter(a), Counter(b)
    pe = sum(ca[k] * cb[k] for k in LABELS) / (n * n)
    return round((po - pe) / (1 - pe), 3) if pe < 1 else 1.0


def leakage_audit(answers: list[dict]) -> dict:
    """What the answer text alone reveals about which system wrote it."""
    signals = {
        "timestamp (mm:ss)": r"\b\d{1,2}:\d{2}\b",
        "Moment RAG gate refusal text": r"no moment of the talk looks related",
        "mentions 'excerpts'": r"\bexcerpts?\b",
        "mentions 'moment(s)'": r"\bmoments?\b",
    }
    out = {}
    for label, pat in signals.items():
        out[label] = {s: sum(bool(re.search(pat, a["answer"] or "", re.I))
                             for a in answers if a["system"] == s) for s in ("baseline", "moment")}
    return out


def compare(src: Path, claude_dir: Path, model: str) -> dict:
    gpt = {(j["id"], j["system"]): j for j in json.loads((src / "judged.json").read_text())}
    cla = {(j["id"], j["system"]): j for j in json.loads((claude_dir / "judged.json").read_text())}
    keys = sorted(gpt.keys() & cla.keys())
    a, b = [gpt[k]["verdict"] for k in keys], [cla[k]["verdict"] for k in keys]
    counts = {judge: {s: {lab: sum(1 for k in keys if k[1] == s and d[k]["verdict"] == lab
                                   and d[k]["type"] != "unanswerable") for lab in LABELS}
                      for s in ("baseline", "moment")}
              for judge, d in (("gpt-5.6-luna", gpt), (model, cla))}
    unans = {judge: {s: sum(1 for k in keys if k[1] == s and d[k]["type"] == "unanswerable"
                            and d[k]["verdict"] == "correct") for s in ("baseline", "moment")}
             for judge, d in (("gpt-5.6-luna", gpt), (model, cla))}
    disagreements = [{"id": k[0], "system": k[1], "type": gpt[k]["type"],
                      "gpt": gpt[k]["verdict"], "claude": cla[k]["verdict"],
                      "claude_reason": cla[k]["reason"]} for k in keys
                     if gpt[k]["verdict"] != cla[k]["verdict"]]
    winner = {j: ("moment" if c["moment"]["correct"] > c["baseline"]["correct"] else
                  "baseline" if c["baseline"]["correct"] > c["moment"]["correct"] else "tie")
              for j, c in counts.items()}
    answers = json.loads((src / "answers.json").read_text())
    return {"answers": src.name, "judges": ["gpt-5.6-luna", model], "n": len(keys),
            "answerable_counts": counts, "unanswerable_declined_correct": unans,
            "agreement_pct": round(100 * sum(x == y for x, y in zip(a, b)) / len(keys), 1),
            "cohen_kappa": cohen_kappa(a, b),
            "judge_errors": sum(1 for k in keys if cla[k].get("judge_error")),
            "headline_winner": winner, "headline_changes": len(set(winner.values())) > 1,
            "disagreements": disagreements, "leakage_audit": leakage_audit(answers)}


def to_md(c: dict) -> str:
    g, m = c["judges"]
    lines = [f"# {c['answers']}: GPT judge vs Claude judge\n",
             f"Same {c['n']} saved answers, same rubric; only the judge model differs.\n",
             "| System | Judge | Correct | Partial | Incorrect | Unanswerable declined |",
             "|---|---|---|---|---|---|"]
    for s in ("baseline", "moment"):
        for j in (g, m):
            k = c["answerable_counts"][j][s]
            lines.append(f"| {s} | {j} | {k['correct']} | {k['partial']} | {k['incorrect']} | "
                         f"{c['unanswerable_declined_correct'][j][s]}/6 |")
    lines += ["", f"- Agreement: **{c['agreement_pct']}%** of {c['n']} verdicts; "
              f"Cohen's kappa **{c['cohen_kappa']}**",
              f"- Headline (more answerable questions correct): GPT judge → "
              f"**{c['headline_winner'][g]}**, Claude judge → **{c['headline_winner'][m]}**; "
              f"conclusion {'CHANGES' if c['headline_changes'] else 'does not change'}",
              f"- Claude judge errors/refusals: {c['judge_errors']}", "",
              "## Disagreements", "", "| Question | System | Type | GPT | Claude | Claude's reason |",
              "|---|---|---|---|---|---|"]
    lines += [f"| {d['id']} | {d['system']} | {d['type']} | {d['gpt']} | {d['claude']} | "
              f"{d['claude_reason'].replace('|', '/')} |" for d in c["disagreements"]]
    lines += ["", "## Leakage audit", "",
              "The judge never sees system names, scores or sources. The answer text itself can "
              "still hint at its source; counts of answers containing each signal:", "",
              "| Signal | Baseline answers | Moment RAG answers |", "|---|---|---|"]
    lines += [f"| {k} | {v['baseline']} | {v['moment']} |" for k, v in c["leakage_audit"].items()]
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("dirs", nargs="*", default=["results/llm-cards", "results/extractive-cards"])
    ap.add_argument("--model", default="claude-opus-5-5")
    args = ap.parse_args()
    client = anthropic.Anthropic()
    for d in args.dirs:
        src = ROOT / d
        out = judge_dir(src, client, args.model)
        c = compare(src, out, args.model)
        (out / "comparison.json").write_text(json.dumps(c, indent=1))
        (out / "comparison.md").write_text(to_md(c))
        print(f"\n{to_md(c)}")


if __name__ == "__main__":
    main()
